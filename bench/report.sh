#!/usr/bin/env bash
# Regenerate bench/results.md: baselines plus, when a predictions file is
# given, pullsift's own out-of-fold predictions.
#
# Usage: bench/report.sh [pullsift-predictions.jsonl]
set -euo pipefail
cd "$(dirname "$0")/.."

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# Rebuild the released files from the archive; refuses to release when the
# corpus violates its own invariants (empty anti-shortcut sources).
python3 bench/build_release.py

python3 bench/baselines/first_timer.py > "$tmp/first_timer.jsonl"
python3 bench/baselines/account_age.py > "$tmp/account_age.jsonl"

{
  echo "# Benchmark results"
  echo
  echo "Generated by bench/report.sh; do not edit. Test split only; see"
  echo "README.md for the protocol and known leaks."
  echo
  n_slop=$(wc -l < bench/corpus/archive/slop.jsonl)
  n_ham=$(wc -l < bench/corpus/archive/ham.jsonl)
  echo "Corpus at generation time: $n_slop slop, $n_ham ham."
  echo
  for entry in "first-timer flag:$tmp/first_timer.jsonl" \
               "account age:$tmp/account_age.jsonl" \
               ${1:+"pullsift (out-of-fold):$1"}; do
    name="${entry%%:*}"
    file="${entry#*:}"
    echo "## $name"
    echo
    echo '```'
    python3 bench/score.py "$file"
    echo '```'
    echo
  done
} > bench/results.md

echo "wrote bench/results.md"
